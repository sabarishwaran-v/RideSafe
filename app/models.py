"""Pydantic data models and schemas for RideSafe API."""

from datetime import datetime, timezone
from enum import Enum
from typing import Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class EventType(str, Enum):
    """Supported event types for device telemetry and alerts."""

    ACCIDENT = "ACCIDENT"
    MANUAL_SOS = "MANUAL_SOS"
    TEST = "TEST"


class EventPayload(BaseModel):
    """Incoming event telemetry schema from ESP32."""

    device_id: str = Field(
        ...,
        min_length=1,
        max_length=64,
        description="Unique identifier of the sending ESP32 device.",
        examples=["RIDESAFE_01"],
    )
    event_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Unique event identifier generated by the device.",
        examples=["evt-20261021-001"],
    )
    event: EventType = Field(
        ...,
        description="Event classification: ACCIDENT or MANUAL_SOS (or TEST for test payloads).",
        examples=["ACCIDENT"],
    )
    latitude: Optional[float] = Field(
        default=None,
        ge=-90.0,
        le=90.0,
        description="Latitude in decimal degrees (-90 to 90).",
        examples=[13.0827],
    )
    longitude: Optional[float] = Field(
        default=None,
        ge=-180.0,
        le=180.0,
        description="Longitude in decimal degrees (-180 to 180).",
        examples=[80.2707],
    )
    altitude: Optional[float] = Field(
        default=None,
        description="Altitude above sea level in meters.",
        examples=[42.5],
    )
    speed_kmph: Optional[float] = Field(
        default=None,
        ge=0.0,
        description="Speed in kilometers per hour (non-negative).",
        examples=[12.7],
    )
    tilt_degrees: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=180.0,
        description="Vehicle tilt angle in degrees (0 to 180).",
        examples=[48.2],
    )
    gps_valid: bool = Field(
        ...,
        description="Indicates whether GPS fix was acquired and coordinates are valid.",
        examples=[True],
    )
    timestamp: datetime = Field(
        ...,
        description="ISO 8601 datetime of the event (accepts naive or timezone-aware ISO formats).",
        examples=["2026-10-21T10:30:00", "2026-10-21T10:30:00Z"],
    )

    @field_validator("timestamp")
    @classmethod
    def normalize_timestamp(cls, v: datetime) -> datetime:
        """Ensure timestamp has timezone information, defaulting to UTC if naive."""
        if v.tzinfo is None:
            return v.replace(tzinfo=timezone.utc)
        return v

    @model_validator(mode="after")
    def validate_gps_coordinates(self) -> "EventPayload":
        """Enforce GPS rules based on gps_valid flag.

        - If gps_valid is true, require valid latitude and longitude.
        - If gps_valid is false, allow latitude and longitude to be null.
        - Never invent GPS coordinates.
        """
        if self.gps_valid:
            if self.latitude is None or self.longitude is None:
                raise ValueError("latitude and longitude are required when gps_valid is true")
        return self


class NotificationDetail(BaseModel):
    """Status details for external notification dispatch (Twilio WhatsApp)."""

    status: str = Field(
        description="Notification status: dispatched, skipped, or failed.",
        examples=["dispatched"],
    )
    provider: str = Field(
        default="twilio_whatsapp",
        description="Notification provider service name.",
    )
    message_sid: Optional[str] = Field(
        default=None,
        description="External Twilio message identifier if accepted by provider.",
        examples=["SMXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXX"],
    )
    delivery_status: str = Field(
        description="Twilio acceptance/delivery status (e.g. queued_by_twilio, failed, not_configured).",
        examples=["queued_by_twilio"],
    )
    recipient: Optional[str] = Field(
        default=None,
        description="Masked recipient WhatsApp phone number.",
        examples=["whatsapp:+91****3210"],
    )
    note: str = Field(
        description="Explanatory message regarding delivery and sandbox state.",
        examples=["Twilio accepted the message for dispatch."],
    )


class AlertResponse(BaseModel):
    """Documented response schema for ingested emergency alert events."""

    status: str = Field(
        default="received",
        description="Backend event processing status (e.g. received).",
    )
    event_id: str = Field(description="Unique identifier of the ingested event.")
    device_id: str = Field(description="Identifier of the reporting device.")
    event: EventType = Field(description="The event type reported.")
    is_test: bool = Field(default=False, description="Whether this is a test event.")
    is_emergency: bool = Field(default=True, description="Whether this event qualifies for emergency routing.")
    received_at: datetime = Field(description="Backend UTC receipt timestamp.")
    storage: str = Field(
        default="sqlite",
        description="Backend storage medium.",
    )
    notification: NotificationDetail = Field(
        description="Status of the WhatsApp alert dispatch attempt.",
    )
    message: str = Field(description="Human-readable processing message.")


class TestMessageResponse(BaseModel):
    """Documented response schema for test events."""

    status: str = Field(
        default="test_acknowledged",
        description="Backend processing status for test events.",
    )
    event_id: str = Field(description="Unique identifier of the test event.")
    device_id: str = Field(description="Identifier of the reporting device.")
    event: EventType = Field(default=EventType.TEST, description="The event type.")
    is_test: bool = Field(default=True, description="Always true for test endpoint.")
    is_emergency: bool = Field(default=False, description="Always false for test endpoint.")
    received_at: datetime = Field(description="Backend UTC receipt timestamp.")
    storage: str = Field(
        default="sqlite",
        description="Backend storage medium.",
    )
    notification: NotificationDetail = Field(
        description="Status of the test WhatsApp dispatch attempt.",
    )
    message: str = Field(description="Human-readable processing message.")


# Backward-compatible alias
EventIngestResponse = AlertResponse


class HealthResponse(BaseModel):
    """Schema for basic service health check response."""

    service: str = Field(examples=["RideSafe Backend"])
    status: str = Field(examples=["healthy"])
    version: Optional[str] = Field(default=None, examples=["1.0.0"])
    message: Optional[str] = Field(default=None, examples=["Service is running"])


class StorageStatus(BaseModel):
    """Status details for event persistence storage."""

    type: str = Field(description="Configured storage engine type (e.g. sqlite).")
    initialized: bool = Field(description="Whether the database schema has been verified/initialized.")
    database_path: str = Field(description="Configured database storage path.")


class TwilioStatus(BaseModel):
    """Status details for Twilio WhatsApp configuration (no credentials exposed)."""

    configured: bool = Field(description="Whether all Twilio credentials are configured.")
    account_sid_present: bool = Field(description="Whether TWILIO_ACCOUNT_SID is set.")
    auth_token_present: bool = Field(description="Whether TWILIO_AUTH_TOKEN is set.")
    whatsapp_from_present: bool = Field(description="Whether TWILIO_WHATSAPP_FROM is set.")
    emergency_contact_present: bool = Field(description="Whether EMERGENCY_WHATSAPP_TO is set.")
    content_sid_configured: bool = Field(
        default=False,
        description="Whether a pre-approved Content Template SID (HX...) is configured.",
    )
    recipient_masked: Optional[str] = Field(
        default=None,
        description="Masked emergency contact number (for verification).",
    )


class SecurityStatus(BaseModel):
    """Status details for API authentication and security."""

    api_key_required: bool = Field(description="Whether RIDESAFE_API_KEY is configured and required.")


class ComponentStatus(BaseModel):
    """Status details for system components."""

    api: str
    esp32_receiver: str
    whatsapp_alert_service: str
    storage: StorageStatus


class ServiceStatusResponse(BaseModel):
    """Schema for comprehensive system status response."""

    status: str
    service: str
    version: str
    environment: str
    phase: str = Field(default="Phase 4 - Twilio WhatsApp Integration")
    components: ComponentStatus
    twilio: TwilioStatus
    security: SecurityStatus


class DatabaseVerificationResponse(BaseModel):
    """Documented response schema for database-only diagnostic verification."""

    status: str = Field(description="Operational status: operational or error.", examples=["operational"])
    storage_type: str = Field(description="Active database backend: postgresql or sqlite.", examples=["postgresql"])
    verified: bool = Field(description="Whether write, read, and delete operations succeeded.", examples=[True])
    message: str = Field(description="Sanitized diagnostic summary.", examples=["Database write, read, and cleanup verified successfully."])
    timestamp: datetime = Field(description="UTC timestamp of the verification run.")


# Backward-compatible alias
SystemStatusResponse = ServiceStatusResponse
